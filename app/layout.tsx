import type { Metadata, Viewport } from 'next'
import { Inter } from 'next/font/google'
import './globals.css'
import { headers } from 'next/headers'
import { DEFAULT_DOMAIN, resolveDomain } from '@/lib/data'
import { DEFAULT_LOCALE, isLocale, LOCALE_META } from '@/lib/i18n'

const inter = Inter({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-inter',
})

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  maximumScale: 5,
  // Matches --background in app/globals.css.
  themeColor: '#fbfbfa',
}

// Only the parts that hold for every route. Everything the visitor actually
// reads - title, description, hreflang alternates - is language-specific and
// therefore generated by app/[locale]/page.tsx, which has the locale in its
// params rather than having to infer it.
//
// `metadataBase` stays here because the file-based metadata routes (icon,
// apple-icon, opengraph-image) resolve their URLs against it and never see the
// page's metadata.
export async function generateMetadata(): Promise<Metadata> {
  const headersList = await headers()
  const domain =
    headersList.get('x-domain') ||
    resolveDomain(headersList.get('host')) ||
    DEFAULT_DOMAIN

  return {
    generator: 'Next.js',
    metadataBase: new URL(`https://${domain}`),
  }
}

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode
}>) {
  const headersList = await headers()
  const domain =
    headersList.get('x-domain') ||
    resolveDomain(headersList.get('host')) ||
    DEFAULT_DOMAIN

  // x-locale is set by the middleware from the /:locale path segment. This
  // layout sits above the segment, so the header is how the locale reaches it;
  // the fallback only applies to requests that bypassed the middleware, which
  // are the ones with no locale in the URL either.
  const headerLocale = headersList.get('x-locale')
  const locale = isLocale(headerLocale) ? headerLocale : DEFAULT_LOCALE

  return (
    <html lang={LOCALE_META[locale].htmlLang} className={inter.variable}>
      <head>
        {/* www.livelox.com is where the links actually point; preconnecting to
            the bare apex would warm up the wrong origin. */}
        <link rel="preconnect" href="https://oresults.eu" />
        <link rel="preconnect" href="https://www.livelox.com" />
        <link rel="dns-prefetch" href="https://oresults.eu" />
        <link rel="dns-prefetch" href="https://www.livelox.com" />
        <meta name="x-domain" content={domain} />
      </head>
      <body className="antialiased">{children}</body>
    </html>
  )
}
